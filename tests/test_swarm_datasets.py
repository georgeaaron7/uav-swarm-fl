import json
import zipfile

import numpy as np
import pytest

from fl.channel_traces import REQUIRED_FIELDS
from swarmcompute.datasets import export_data, verify_data
from swarmcompute.shared.hashing import sha256
from swarmcompute.worker.executor import dataset_directory


def test_offline_data_handoff_full_pilot_and_source_validation(tmp_path):
    source = tmp_path / "source"
    source.mkdir()
    np.savez_compressed(
        source / "cifar10.npz",
        x_train=np.zeros((2200, 32, 32, 3), dtype=np.uint8),
        y_train=np.arange(2200) % 10,
        x_test=np.zeros((600, 32, 32, 3), dtype=np.uint8),
        y_test=np.arange(600) % 10,
    )
    trace = source / "channel_traces/deepsense23.npz"
    trace.parent.mkdir()
    np.savez_compressed(
        trace,
        **{
            key: np.zeros(400, dtype=int)
            if key == "sequence_id"
            else np.arange(400, dtype=float)
            for key in REQUIRED_FIELDS
        },
    )
    report = export_data(source, tmp_path / "worker-data.zip")
    assert report["sha256"] == sha256(tmp_path / "worker-data.zip")
    destination = tmp_path / "windows-worker"
    with zipfile.ZipFile(report["path"]) as archive:
        archive.extractall(destination)  # only the archive generated by this test
    data = destination / "data"
    assert verify_data(data)["valid"]
    pilot_hash = sha256(data / "context_pilot/cifar10.npz")
    assert dataset_directory({"data_dir": str(data)}, pilot_hash) == str(
        data / "context_pilot"
    )
    full_hash = sha256(data / "cifar10.npz")
    assert pilot_hash != full_hash
    assert dataset_directory({"data_dir": str(data)}, full_hash) == str(data)
    with pytest.raises(FileExistsError):
        export_data(source, tmp_path / "worker-data.zip")
    manifest_path = data / "swarm-data-manifest.json"
    manifest = json.loads(manifest_path.read_text())
    manifest["source_sha256"] = "different"
    manifest_path.write_text(json.dumps(manifest))
    assert not verify_data(data)["valid"]
    manifest["files"][0]["path"] = "../unrelated"
    manifest_path.write_text(json.dumps(manifest))
    with pytest.raises(ValueError, match="paths"):
        verify_data(data)
